#include "headers.h"
void timer3_start()
{
	RCC_APB1ENR|=TIM3_EN;
	TIM3_CNT=0;
	TIM3_PSC=83;
	TIM3_ARR=999;
	TIM3_DIER|=TIM3_UIE;
	NVIC_ISER0|=TIM3_IRQ;
	TIM3_CR1|=TIM3_ARPE;

}
void timer3_ch1(uint32_t duty_cycle)
{
	RCC_AHB1ENR|=GPIOA_EN;
	GPIOA_MODER&=PA6_MODE_CLEAR;
	GPIOA_MODER|=PA6_AF_MODE ;
	GPIOA_AFRL&=PA6_AF_CLEAR ;
	GPIOA_AFRL|=PA6_TIM3_AF ;
	timer3_start();
	TIM3_CCMR1&=CH1_OCM_CLEAR;
	TIM3_CCMR1|=CH1_PWM_MODE;
	TIM3_CCMR1|=CH1_OC_PRELOAD;
	TIM3_CCER&=CH1_CC_POLARITY;
	TIM3_CCER|=CH1_CC_ENABLE;
	TIM3_CCR1=duty_cycle;
	TIM3_EGR|=TIM3_UPDATE_EVENT;
	TIM3_CR1|=TIM3_COUNTER_ENABLE;
}
